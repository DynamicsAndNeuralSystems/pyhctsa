"""Generate the Monte Carlo null table of the slowest SFA eigenvalue used by ``slow_feature_analysis``.

Design:

* Null: the W x 5 matrix of per-window statistics has iid rows (windows exchangeable, no slow
  structure). Each column is replaced by the normal scores of its ranks across windows,
  ``norm.ppf((rank + 0.5) / W)``, exactly as ``slow_feature_analysis`` does, so the null does not
  depend on the marginal distribution of any statistic; the rows are drawn as iid N(0, I_5).
* Statistic: eta1, the smallest eigenvalue of the covariance of the first differences of the
  whitened (PCA-whitened, all 5 directions) window-statistic matrix -- the SFA slowness of the
  slowest feature. Small eta1 = slow variation across windows.
* Window counts W_NODES = 10, 20, 40, ..., 1280; R = 4,000,000 replications each.
  QUANTILES[i, j] = the PROBS[j] quantile of eta1 at W_NODES[i] (numpy default 'linear' method),
  with PROBS log-spaced from 1e-5 to 1 (101 values; PROBS[-1] = 1 gives the sample maximum).
  Replications whose standardized-statistic covariance is numerically singular (possible only for
  small W, where two rank columns can coincide) are discarded, as the function skips such a scale.
* RNG: numpy PCG64. Each W is split into N_BLOCKS blocks of R / N_BLOCKS replications run in
  parallel; block b of size W uses ``np.random.default_rng([20261107, 3, W, b])`` and draws
  ``standard_normal((m, W, 5))`` in consecutive chunks. Deterministic whatever the worker count.

Usage:  python scripts/gen_sfa_null_table.py [out_path] [n_workers]
"""
import os
import sys
import time
import datetime
from multiprocessing import Pool

for _v in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "VECLIB_MAXIMUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

import numpy as np
from scipy.special import ndtri

SEED = 20261107
STREAM = 3
R = 4_000_000
N_BLOCKS = 20
W_NODES = [10 * 2 ** j for j in range(8)]   # 10 .. 1280
PROBS = np.logspace(-5, 0, 101)
SING_TOL = 1e-10


def _eta1(M):
    """eta1 for a batch M of shape (m, W, 5) of iid rows; NaN where the covariance is singular."""
    m, W, _ = M.shape
    ranks = M.argsort(axis=1).argsort(axis=1)
    X = ndtri((ranks + 0.5) / W)
    Xc = X - X.mean(axis=1, keepdims=True)
    C = np.einsum('bwi,bwj->bij', Xc, Xc) / (W - 1)
    e, V = np.linalg.eigh(C)
    ok = e[:, 0] > SING_TOL * e[:, -1]
    out = np.full(m, np.nan)
    Z = np.einsum('bwi,bij->bwj', Xc[ok], V[ok]) / np.sqrt(e[ok])[:, None, :]
    D = np.diff(Z, axis=1)
    D -= D.mean(axis=1, keepdims=True)
    Cd = np.einsum('bwi,bwj->bij', D, D) / (W - 2)
    out[ok] = np.linalg.eigvalsh(Cd)[:, 0]
    return out


def _block(args):
    W, b = args
    reps = R // N_BLOCKS
    rng = np.random.default_rng([SEED, STREAM, W, b])
    chunk = max(1, int(2_000_000 // (5 * W)))
    out = np.empty(reps)
    done = 0
    while done < reps:
        m = min(chunk, reps - done)
        out[done:done + m] = _eta1(rng.standard_normal((m, W, 5)))
        done += m
    return W, b, out


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else 'pyhctsa/operations/_sfa_null_table.py'
    nw = int(sys.argv[2]) if len(sys.argv) > 2 else 6
    t0 = time.time()
    tasks = [(W, b) for W in sorted(W_NODES, reverse=True) for b in range(N_BLOCKS)]
    reps = R // N_BLOCKS
    samples = {W: np.empty(R) for W in W_NODES}
    filled = {W: 0 for W in W_NODES}
    Q = np.empty((len(W_NODES), len(PROBS)))
    n_sing = {}
    with Pool(nw) as pool:
        for W, b, res in pool.imap_unordered(_block, tasks):
            samples[W][b * reps:(b + 1) * reps] = res
            filled[W] += 1
            if filled[W] == N_BLOCKS:
                s = samples.pop(W)
                n_sing[W] = int(np.isnan(s).sum())
                Q[W_NODES.index(W)] = np.quantile(s[~np.isnan(s)], PROBS)
                print(f'W = {W}: done ({time.time() - t0:.0f} s, {n_sing[W]} singular)', flush=True)
    elapsed = time.time() - t0
    with open(out_path, 'w') as f:
        f.write('"""Monte Carlo null quantiles of the slowest SFA eigenvalue, eta1 (generated file).\n\n'
                'Generated by scripts/gen_sfa_null_table.py -- do not edit by hand.\n'
                f'seed = [{SEED}, {STREAM}, W, block], R = {R} replications per W ({N_BLOCKS} blocks), '
                f'numpy {np.__version__}, {datetime.date.today()}, {elapsed:.0f} s.\n'
                'Null: W x 5 window statistics with iid rows, each column rank-transformed to normal scores.\n'
                'PROBS: 101 probabilities log-spaced from 1e-5 to 1.\n'
                'QUANTILES[i, j] = PROBS[j] quantile of eta1 for W_NODES[i] windows.\n'
                f'Singular replications discarded per W: {n_sing}.\n"""\n\n'
                'import numpy as np\n\n')
        f.write(f'W_NODES = np.array({W_NODES!r})\n\n')
        f.write('PROBS = np.logspace(-5, 0, 101)\n\n')
        f.write('QUANTILES = np.array([\n')
        for row in Q:
            f.write('    [' + ', '.join(f'{v:.8g}' for v in row) + '],\n')
        f.write('])\n')
    print('done in %.0f s -> %s' % (elapsed, out_path))


if __name__ == '__main__':
    main()
