"""Generate the Monte Carlo critical-value table for the Jarque-Bera statistic.

Design:

* Null: x_1..x_n iid N(0, 1); JB = (n/6)(S^2 + (K - 3)^2 / 4) with biased sample moments
  (Jarque & Bera 1987).
* Sample sizes N_NODES, R = 4,000,000 replications each, and significance levels ALPHAS covering
  the whole open interval (0, 1): uniformly spaced in logit(alpha) from 1e-4 to 1 - 1e-4
  (321 values), so both tails are resolved. CV[i, j] = quantile(JB(n_i), 1 - ALPHAS[j])
  (numpy default 'linear' method). Beyond the table the p-value is extrapolated by
  ``_jbtest_pvalue`` (log-linear in the far upper tail; linear to p = 1 at JB = 0).
* RNG: numpy PCG64.  Each n is split into N_BLOCKS blocks of R / N_BLOCKS replications run
  in parallel; block b of size n uses ``np.random.default_rng([20261008, 2, n, b])`` and draws
  ``standard_normal((m, n))`` in consecutive row chunks.  Deterministic whatever the worker count.

Usage:  python scripts/gen_jbtest_null_table.py [out_path] [n_workers]
"""
import os
import sys
import time
import datetime
from multiprocessing import Pool

for _v in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "VECLIB_MAXIMUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")

import numpy as np

SEED = 20261008
STREAM = 2
R = 4_000_000
N_BLOCKS = 10
N_NODES = [3, 4, 5, 6, 7, 8, 9, 10, 12, 15, 20, 25, 30, 40, 50, 60, 80, 100, 125, 150, 200, 250,
           300, 400, 500, 750, 1000, 1500, 2000]
_LOGIT_MAX = float(np.log((1.0 - 1e-4) / 1e-4))
ALPHAS = 1.0 / (1.0 + np.exp(-np.linspace(-_LOGIT_MAX, _LOGIT_MAX, 321)))   # increasing, symmetric about 1/2


def _jb(x):
    n = x.shape[1]
    x = x - x.mean(axis=1, keepdims=True)
    x2 = x * x
    m2 = x2.mean(axis=1)
    m3 = (x2 * x).mean(axis=1)
    m4 = (x2 * x2).mean(axis=1)
    S = m3 / m2 ** 1.5
    K = m4 / m2 ** 2
    return n / 6.0 * (S ** 2 + (K - 3.0) ** 2 / 4.0)


def _block(args):
    n, b = args
    reps = R // N_BLOCKS
    rng = np.random.default_rng([SEED, STREAM, n, b])
    chunk = max(1, int(1_000_000 // n))
    out = np.empty(reps)
    done = 0
    while done < reps:
        m = min(chunk, reps - done)
        out[done:done + m] = _jb(rng.standard_normal((m, n)))
        done += m
    return n, b, out


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else 'pyhctsa/toolboxes/distribution_fits/_jbtest_null_table.py'
    nw = int(sys.argv[2]) if len(sys.argv) > 2 else 6
    t0 = time.time()
    tasks = [(n, b) for n in sorted(N_NODES, reverse=True) for b in range(N_BLOCKS)]
    reps = R // N_BLOCKS
    samples = {n: np.empty(R) for n in N_NODES}
    filled = {n: 0 for n in N_NODES}
    CV = np.empty((len(N_NODES), len(ALPHAS)))
    with Pool(nw) as pool:
        for n, b, res in pool.imap_unordered(_block, tasks):
            samples[n][b * reps:(b + 1) * reps] = res
            filled[n] += 1
            if filled[n] == N_BLOCKS:      # all blocks of this n are in: reduce and free the samples
                CV[N_NODES.index(n)] = np.quantile(samples.pop(n), 1.0 - ALPHAS)
    elapsed = time.time() - t0
    with open(out_path, 'w') as f:
        f.write('"""Monte Carlo upper-tail critical values of the Jarque-Bera statistic (generated file).\n\n'
                'Generated by scripts/gen_jbtest_null_table.py -- do not edit by hand.\n'
                f'seed = [{SEED}, {STREAM}, n, block], R = {R} replications per n ({N_BLOCKS} blocks), '
                f'numpy {np.__version__}, {datetime.date.today()}, {elapsed:.0f} s.\n'
                'ALPHAS: 321 significance levels, uniform in logit from 1e-4 to 1 - 1e-4.\n'
                'CRITICAL_VALUES[i, j] = (1 - ALPHAS[j]) quantile of JB for iid normal samples of size N_NODES[i].\n"""\n\n'
                'import numpy as np\n\n')
        f.write(f'N_NODES = np.array({N_NODES!r}, dtype=float)\n\n')
        f.write('_LOGIT_MAX = float(np.log((1.0 - 1e-4) / 1e-4))\n'
                'ALPHAS = 1.0 / (1.0 + np.exp(-np.linspace(-_LOGIT_MAX, _LOGIT_MAX, 321)))\n\n')
        f.write('CRITICAL_VALUES = np.array([\n')
        for row in CV:
            f.write('    [' + ', '.join(f'{v:.8g}' for v in row) + '],\n')
        f.write('])\n')
    print('done in %.0f s -> %s' % (elapsed, out_path))


if __name__ == '__main__':
    main()
