def assert_bitwise_equal(a, b):
    """
    Assert exact bitwise equality between two float64 arrays.

    Useful when regression-testing optimized solver implementations against the
    original implementation.
    """
    a = np.asarray(
        a,
        dtype=np.float64,
    )

    b = np.asarray(
        b,
        dtype=np.float64,
    )

    np.testing.assert_array_equal(
        a.view(np.uint64),
        b.view(np.uint64),
    )