def goodness_of_fit(
    y,
    y_fit,
    num_coeffs,
):
    """
    Goodness-of-fit statistics matching the ``gof`` struct returned by
    MATLAB's ``fit``.

    Note that ``rmse`` is the standard error

        sqrt(SSE / dfe)

    rather than the root-mean-square of the residuals.

    Parameters
    ----------
    y : array-like
        Observed values.

    y_fit : array-like
        Fitted values.

    num_coeffs : int
        Number of fitted coefficients, which determines the error degrees of
        freedom.

    Returns
    -------
    dict
        Keys are ``sse``, ``rsquare``, ``adjrsquare`` and ``rmse``.
    """
    y = np.asarray(
        y,
        dtype=float,
    )

    y_fit = np.asarray(
        y_fit,
        dtype=float,
    )

    n = len(y)
    dfe = n - num_coeffs

    residual = (
        y - y_fit
    )

    sse = np.sum(
        residual**2
    )

    centered = (
        y - np.mean(y)
    )

    sst = np.sum(
        centered**2
    )

    rsquare = (
        1 - sse / sst
    )

    return {
        "sse": sse,
        "rsquare": rsquare,
        "adjrsquare": (
            1
            - (
                1 - rsquare
            )
            * (n - 1)
            / dfe
        ),
        "rmse": np.sqrt(
            sse / dfe
        ),
    }


